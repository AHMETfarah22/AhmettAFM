// Make Floating Call Button Draggable (Mouse + Touch)
function initDraggableWidget() {
    const el = document.getElementById('draggable-call-btn');
    if (!el) return;

    let isDragging = false;
    let hasMoved = false;
    let startX = 0, startY = 0;
    let initialLeft = 0, initialTop = 0;

    function getCoords(e) {
        if (e.touches && e.touches.length > 0) {
            return { x: e.touches[0].clientX, y: e.touches[0].clientY };
        }
        return { x: e.clientX, y: e.clientY };
    }

    function onStart(e) {
        const rect = el.getBoundingClientRect();
        initialLeft = rect.left;
        initialTop = rect.top;

        const coords = getCoords(e);
        startX = coords.x;
        startY = coords.y;

        isDragging = true;
        hasMoved = false;

        el.style.cursor = 'grabbing';
        el.style.transition = 'none';
    }

    function onMove(e) {
        if (!isDragging) return;

        const coords = getCoords(e);
        const deltaX = coords.x - startX;
        const deltaY = coords.y - startY;

        if (Math.abs(deltaX) > 5 || Math.abs(deltaY) > 5) {
            hasMoved = true;
        }

        if (hasMoved) {
            if (e.cancelable) e.preventDefault();

            let newLeft = initialLeft + deltaX;
            let newTop = initialTop + deltaY;

            const maxLeft = window.innerWidth - el.offsetWidth - 10;
            const maxTop = window.innerHeight - el.offsetHeight - 10;

            newLeft = Math.max(10, Math.min(newLeft, maxLeft));
            newTop = Math.max(10, Math.min(newTop, maxTop));

            el.style.left = `${newLeft}px`;
            el.style.top = `${newTop}px`;
            el.style.right = 'auto';
            el.style.bottom = 'auto';
            el.style.position = 'fixed';
        }
    }

    function onEnd() {
        if (!isDragging) return;
        isDragging = false;
        el.style.cursor = 'grab';
        el.style.transition = 'all 0.3s ease';
    }

    // Prevent call navigation if dragged
    el.addEventListener('click', (e) => {
        if (hasMoved) {
            e.preventDefault();
            e.stopPropagation();
        }
    });

    // Mouse Events
    el.addEventListener('mousedown', onStart);
    window.addEventListener('mousemove', onMove);
    window.addEventListener('mouseup', onEnd);

    // Touch Events for Mobile
    el.addEventListener('touchstart', onStart, { passive: false });
    window.addEventListener('touchmove', onMove, { passive: false });
    window.addEventListener('touchend', onEnd);
}

