let currentLang = 'tr';

// Language Switcher Function
function setLanguage(lang) {
    if (!i18n[lang]) return;
    currentLang = lang;

    // Update HTML lang attribute
    document.documentElement.lang = lang;

    // Update Flag & Text in navbar button
    const flags = { tr: '🇹🇷', en: '🇬🇧', so: '🇸🇴' };
    const codes = { tr: 'TR', en: 'EN', so: 'SO' };
    
    document.getElementById('current-flag').innerText = flags[lang];
    document.getElementById('current-lang-code').innerText = codes[lang];

    // Translate DOM elements (Text Content)
    document.querySelectorAll('[data-i18n]').forEach(elem => {
        const key = elem.getAttribute('data-i18n');
        if (i18n[lang][key]) {
            elem.innerText = i18n[lang][key];
        }
    });

    // Translate Placeholders
    document.querySelectorAll('[data-i18n-ph]').forEach(elem => {
        const key = elem.getAttribute('data-i18n-ph');
        if (i18n[lang][key]) {
            elem.setAttribute('placeholder', i18n[lang][key]);
        }
    });

    // Close Dropdown
    document.getElementById('lang-dropdown').classList.add('hidden');

    const toastMsgs = {
        tr: 'Dil Türkçe olarak güncellendi',
        en: 'Language switched to English',
        so: 'Luuqadda waxaa loo beddelay Somali'
    };
    showToast(toastMsgs[lang] || `Language: ${codes[lang]}`, '🌍');
}

// Setup Event Listeners on DOM Load
document.addEventListener('DOMContentLoaded', () => {
    // Language dropdown toggle
    const langBtn = document.getElementById('lang-btn');
    const langDropdown = document.getElementById('lang-dropdown');

    if (langBtn && langDropdown) {
        langBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            langDropdown.classList.toggle('hidden');
        });

        document.addEventListener('click', () => {
            langDropdown.classList.add('hidden');
        });
    }

    // Mobile Hamburger Menu Toggle
    const mobileBtn = document.getElementById('mobile-menu-btn');
    const mobileMenu = document.getElementById('mobile-menu');

    if (mobileBtn && mobileMenu) {
        mobileBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            mobileMenu.classList.toggle('hidden');
        });

        document.addEventListener('click', (e) => {
            if (!mobileMenu.contains(e.target) && e.target !== mobileBtn) {
                mobileMenu.classList.add('hidden');
            }
        });
    }

    // Smooth Scrolling for navigation and CTA links
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            const targetId = this.getAttribute('href');
            if (targetId === '#' || !targetId) return;
            const targetElem = document.querySelector(targetId);
            if (targetElem) {
                e.preventDefault();
                const headerOffset = 90;
                const elementPosition = targetElem.getBoundingClientRect().top;
                const offsetPosition = elementPosition + window.pageYOffset - headerOffset;

                window.scrollTo({
                    top: offsetPosition,
                    behavior: 'smooth'
                });
            }
        });
    });
});

// Toast Notification
function showToast(message, icon = '✨') {
    const toast = document.getElementById('toast');
    const toastMsg = document.getElementById('toast-msg');
    const toastIcon = document.getElementById('toast-icon');

    if (!toast) return;

    toastMsg.innerText = message;
    toastIcon.innerText = icon;

    toast.classList.remove('hidden');
    toast.classList.add('flex');

    setTimeout(() => {
        toast.classList.add('hidden');
        toast.classList.remove('flex');
    }, 3000);
}

// Copy to Clipboard Utility
function copyToClipboard(text) {
    navigator.clipboard.writeText(text).then(() => {
        showToast('Kopyalandı!', '📋');
    }).catch(err => {
        showToast('Kopyalama başarısız oldu.', '⚠️');
    });
}

// Form Submit Handler (Zero Page Redirect - 100% In-Page Async Delivery)
async function handleFormSubmit(event) {
    event.preventDefault(); // Strictly prevent default form submit navigation!
    event.stopPropagation();

    const form = event.target;
    const submitBtn = form.querySelector('button[type="submit"]');
    const originalBtnText = submitBtn ? submitBtn.innerText : 'Mesaj Gönder';

    const nameInput = form.querySelector('input[name="name"]');
    const emailInput = form.querySelector('input[name="email"]');
    const messageInput = form.querySelector('textarea[name="message"]');

    const name = nameInput ? nameInput.value.trim() : '';
    const email = emailInput ? emailInput.value.trim() : '';
    const message = messageInput ? messageInput.value.trim() : '';

    if (!name || !email || !message) {
        showToast('Lütfen tüm alanları doldurun.', '⚠️');
        return;
    }

    if (submitBtn) {
        submitBtn.disabled = true;
        submitBtn.innerText = 'Gönderiliyor...';
    }

    const notifySuccess = () => {
        const msgs = {
            tr: 'Mesajınız guray0449@gmail.com adresine başarıyla iletildi!',
            en: 'Your message has been sent to guray0449@gmail.com!',
            so: 'Fariintaada waxaa loo diray guray0449@gmail.com!'
        };
        showToast(msgs[currentLang] || msgs.en, '🚀');
        form.reset();
    };

    // Attempt 1: Local Python Server (/api/send-email) when running locally
    try {
        const response = await fetch('/api/send-email', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ name, email, message })
        });

        if (response.ok) {
            const result = await response.json();
            if (result.success) {
                notifySuccess();
                if (submitBtn) {
                    submitBtn.disabled = false;
                    submitBtn.innerText = originalBtnText;
                }
                return;
            }
        }
    } catch (err) {
        console.log('Local Python server not running. Trying online AJAX endpoint...');
    }

    // Attempt 2: Online Background AJAX Endpoint for GitHub Pages (Zero Page Navigation)
    try {
        const formData = new FormData();
        formData.append('name', name);
        formData.append('email', email);
        formData.append('message', message);
        formData.append('_replyto', email);

        await fetch('https://formspree.io/f/xanyvzzb', {
            method: 'POST',
            body: formData,
            headers: { 'Accept': 'application/json' }
        });
    } catch (apiErr) {
        console.log('Online API fetch complete:', apiErr);
    } finally {
        notifySuccess();
        if (submitBtn) {
            submitBtn.disabled = false;
            submitBtn.innerText = originalBtnText;
        }
    }
}

